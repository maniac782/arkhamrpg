const known = l => Object.prototype.hasOwnProperty.call(M, l) ? l : 'en';
// msg('pl', 'comingUp', {name}): the message in that language with its {names} filled in
function msg(lang, key, vars) {
  const s = M[known(lang)][key] || M.en[key] || key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? vars[k] : m));
}
const locale = lang => LOCALE[known(lang)];
module.exports = {msg, locale, known, MESSAGES: M};
